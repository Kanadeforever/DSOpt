#pragma once

// =============================================================================
// logging_types.hpp
// -----------------------------------------------------------------------------
// 该文件只定义模块之间共用的日志回调类型，避免各功能模块直接依赖具体的
// 日志实现。功能模块只需要调用回调，不需要知道日志写入磁盘、调试器或其他
// 输出目标的具体细节。
// =============================================================================

namespace Common {

// 日志回调约定：
// - 参数必须是以 L'\0' 结尾的宽字符串；
// - 运行时日志统一使用简体中文；
// - 回调可以为空，模块必须在调用前检查；
// - 回调不接管字符串所有权，调用结束后字符串仍由调用者管理。
using LogCallback = void (*)(const wchar_t* message);

} // namespace Common
